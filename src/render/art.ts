/**
 * 벡터 아트 — 밤길 방어전.
 *
 * 외부 스프라이트를 쓰지 않고 SVG 패스 데이터를 직접 들고 있다가 `Path2D`로
 * 그린다. 이렇게 하면
 *   - 에셋 파일도 로딩도 없다 (아티팩트로 통째로 배포해도 자체 완결)
 *   - 해상도에 무관하게 선명하다
 *   - `@color` 같은 토큰으로 같은 그림에 데이터의 색을 입힐 수 있다
 *
 * 모든 그림은 **32×32 좌표계**로 그리고, 바닥이 y≈29에 오도록 맞춘다.
 * 그래야 타일 위에 "서 있는" 것처럼 보인다. 시점은 위에서 살짝 내려다보는
 * 측면(3/4)이다.
 *
 * ─────────────────────────────────────────────────────────────────────
 * 고증 메모
 *
 * 소재는 한국 민속이다. 자료를 찾아보고 그린 것과, 자료가 없어 추정한 것을
 * 구분해 둔다. 나중에 누가 고칠 때 어디를 의심해야 하는지가 남아야 한다.
 *
 * 확인하고 그린 것
 *   장승   중부 지역 남장승은 사모(紗帽)를 쓰고 눈알과 코가 툭 불거진 채
 *          이를 드러낸다. 퉁방울눈, 주름 잡힌 주먹코, 입가의 송곳니,
 *          입 밑의 땋은 수염. 악귀를 쫓으려 험상궂으면서도 익살스럽게 만든다.
 *   솟대   긴 장대 위에 나무 새(오리·기러기)를 얹는다. 마을 입구에 벽사로 세운다.
 *   서낭당 신목(神樹) 아래 원추형 돌무더기, 나무와 돌무더기에 천 조각을 늘어뜨린다.
 *   부적   직사각형 **누런 괴황지에 붉은 경면주사**로 쓴다.
 *   팥     붉은 팥은 벽사의 힘이 있다고 믿어 잡귀를 쫓는 데 썼다.
 *          동짓날 팥죽을 대문·부엌·벽·마당에 뿌려 잡귀의 출입을 막았다.
 *   청사초롱 푸른 몸통에 위아래를 붉게 두른다. 홍색은 양, 청색은 음.
 *   도깨비 한복 차림에 **패랭이**를 쓰고 다리가 하나이며 **나무** 방망이를 든다.
 *          뿔 달린 붉은 도깨비는 일본 오니의 이미지가 섞인 것이라 쓰지 않았다.
 *   두억시니 덩치가 산만하고 머리카락은 불이 붙은 듯하며 눈은 충혈되어 있고
 *          손톱이 길다. 야차 계열의 사납고 힘센 귀신.
 *   삼두구미 제주 전승의 여우 요괴. 이름 그대로 머리 셋에 꼬리 아홉.
 *   불가사리 쇠를 먹고 자라며 죽일 수 없다. 몸이 단단하고 털이 바늘처럼 뾰족하다.
 *   그슨대 어둠이 실체화한 것. 가랑이를 벌리고 선 채 나타나며 볼수록 커진다.
 *   무구   오색 깃발·방울·삼지창은 굿에 실제로 쓰는 무구다.
 *
 * 추정해서 그린 것 (자료 없음 — 고칠 여지가 큰 부분)
 *   저승사자 검은 갓 + 검은 도포 + 하얀 얼굴은 **1970년대 「전설의 고향」이
 *          만든 이미지**다. 옛 기록의 저승사자는 시왕도 계열의 검은 옷 정도만
 *          확인된다. 그래도 이 그림을 쓴 이유는 한국 사람에게 "저승사자"가
 *          한 번에 읽히는 형태가 이것뿐이기 때문이다 — 고증보다 가독성을 택했다.
 *   귀졸   시왕도의 지옥 옥졸에서 갑주와 철퇴만 가져왔다. 세부는 창작이다.
 *   석장승의 넋 / 허깨비 / 원귀는 특정 전승이 아니라 계열에서 뽑은 형상이다.
 */

export interface ArtLayer {
  /** SVG path 데이터 (viewBox 0 0 32 32) */
  d: string
  /** 채움색. `@color` / `@accent`는 호출부 색으로 치환된다 */
  fill?: string
  stroke?: string
  width?: number
}

export type Art = readonly ArtLayer[]

export interface Tint {
  color: string
  accent: string
}

