/**
 * 벡터 아트 — 조선 방어전.
 *
 * 외부 스프라이트를 쓰지 않고 SVG 패스 데이터를 직접 들고 있다가 `Path2D`로
 * 그린다. 이렇게 하면
 *   - 에셋 파일도 로딩도 없다 (아티팩트로 통째로 배포해도 자체 완결)
 *   - 해상도에 무관하게 선명하다
 *   - `@color` 같은 토큰으로 같은 그림에 데이터의 색을 입힐 수 있다
 *
 * 모든 그림은 **32×32 좌표계**로 그리고, 바닥이 y≈29에 오도록 맞춘다.
 * 그래야 타일 위에 "서 있는" 것처럼 보인다. 시점은 위에서 살짝 내려다보는
 * 측면(3/4)이다. 면은 평평한 단색만 칠하고 **명암·재질감은 렌더러가**
 * 얹는다 (아래 `buildShaded`).
 *
 * ─────────────────────────────────────────────────────────────────────
 * 고증 메모
 *
 * 소재는 조선의 전쟁이다. 왜구의 노략에서 병자호란까지, 실제로 쓰인 무기와
 * 실제로 겪은 적을 그린다. 자료로 확인한 것과 추정한 것을 구분해 둔다 —
 * 나중에 누가 고칠 때 어디를 의심해야 하는지가 남아야 한다.
 *
 * 확인하고 그린 것
 *   각궁     물소뿔·쇠심·뽕나무를 겹친 만곡궁. 시위를 걸면 반대로 휘어
 *            깊은 이중 곡선이 된다. 조선의 주력 무기는 끝까지 활이었다.
 *   편전     통아(桶兒)에 넣어 쏘는 애기살. 짧아서 더 멀리, 더 깊이 박힌다.
 *   전립     군졸이 쓰던 벙거지. 넓은 챙에 둥근 대우, 꼭대기에 상모와 술.
 *   승자총통 1575년 김지가 만든 개인 화기. 나무 자루(木柄)를 끼워 쏘고
 *            총신에 놋쇠 테를 둘렀다.
 *   신기전   화살에 종이 약통을 묶은 로켓. 대신기전은 사거리가 1km를 넘었다.
 *   화차     1451년 문종이 개량. 수레 위 신기전기에 **구멍 100개**를 뚫어
 *            한 번에 쏜다. 고정 거치식이라 방향을 바꾸려면 수레째 돌려야 한다.
 *   거마작   통나무를 X자로 엮어 세운 대기병 방책. 기병의 돌격을 끊는다.
 *   마름쇠   어떻게 던져도 가시 하나가 위를 향하는 네 갈래 쇠못. 사람 발과
 *            말굽을 상하게 한다. 갑옷과 아무 상관이 없다.
 *   비격진천뢰 1592년 이장손이 만든 시한 작렬탄. 무쇠 구 안에 화약과 쇳조각을
 *            넣고 죽통 심지의 길이로 터질 때를 맞춘다. 대완구로 쏜다.
 *   찰갑     작은 미늘을 가죽끈으로 이어 붙인 갑옷. 두정갑은 천 안쪽에 철편을
 *            대고 겉에 못머리만 보이게 한 것.
 *   수자기   진영 대장의 깃발. 누런 바탕에 검은 「帥」 한 글자.
 *   당세구족 왜군 갑옷. 옻칠한 흉갑, 앞뒤로 늘어뜨린 초승달 앞장식의 투구.
 *
 * 추정해서 그린 것 (자료가 얇거나 단순화가 필요했던 부분)
 *   적 병졸의 세부는 특정 부대의 재현이 아니라 **역할**의 기호다. 졸병·척후·
 *   갑병·별동대는 왜구·왜군·후금·청에 모두 있던 병종이라 어느 한쪽의 복식으로
 *   그리지 않았다. 나라가 드러나야 하는 것은 스테이지 이름과 보스이지
 *   잡졸이 아니다.
 *   충차의 지붕과 바퀴 비례는 조선 기록화가 아니라 동아시아 공성 병기 일반에서
 *   가져왔다.
 *
 * 일부러 하지 않은 것
 *   **실존 인물을 보스로 만들지 않았다.** 병자호란의 총사령은 청 태종이지만,
 *   최종 보스는 「팔기 대장」이라는 직책으로만 둔다. 400년 전 사람이라 해도
 *   실명을 붙여 때려잡는 표적으로 삼는 것은 이 게임이 할 일이 아니다.
 */

export interface ArtLayer {
  /** SVG path 데이터 (viewBox 0 0 32 32) */
  d: string
  /** 채움색. `@color` / `@accent`는 호출부 색으로 치환된다 */
  fill?: string
  stroke?: string
  width?: number
}

export type Art = readonly ArtLayer[]

export interface Tint {
  color: string
  accent: string
}

