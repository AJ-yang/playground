/**
 * 적 아트.
 *
 * 타워와 같은 3/4 측면 시점이고, 진행 방향에 따라 좌우로 뒤집어 그린다.
 *
 * 중요 — **실루엣 규칙은 그대로다.** 각 적의 외곽이 원래의 도형 계열로
 * 읽히도록 잡았고(둥근 허깨비 / 앞으로 쏠린 장산범 / 각진 귀졸 /
 * 위아래로 뾰족한 원귀 / 방패 실루엣의 불가사리 / 가시 돋은 보스),
 * 뒤에는 같은 도형의 어두운 한 겹이 깔린다. 색각 이상 사용자가 방어 유형을
 * 판단하는 근거가 색이면 안 되기 때문이다.
 */
const r1 = (v: number) => v.toFixed(1)

/**
 * 여우 꼬리 다발을 만든다. 구미호와 삼두구미가 같은 함수를 쓴다.
 *
 * 처음에는 가는 선 아홉 개에 삼각형 끝을 붙였는데, 나온 그림은 **공작**이었다.
 * 균일한 각도로 180° 부채꼴을 이루고 끝이 뾰족하면 털이 아니라 깃으로 읽힌다.
 * 그래서 네 가지를 바꿨다.
 *   1. 부채각을 100° 안쪽으로 좁히고 전부 **뒤 한 방향**으로 눕힌다
 *   2. 길이 대비 굵기를 키운다. 두 번째 시도에서 밑동만 굵고 끝으로 갈수록
 *      뾰족해지는 도형으로 그렸더니 이번엔 **가시**가 됐다 — 가늘고 길며 끝이
 *      한 점으로 모이는 것은 색을 어떻게 칠해도 털로 안 읽힌다. 그래서
 *      **둥근 끝을 가진 굵기 일정한 선**으로 바꿨다. 여우 꼬리는 실제로도
 *      밑동부터 끝까지 고르게 북슬북슬하다.
 *   3. 길이를 들쭉날쭉하게 해 부채의 규칙성을 깬다
 *   4. 끝을 **흰 털뭉치**로 마감한다 — 붉은여우의 꼬리 끝이 실제로 흰색이라
 *      고증에도 어긋나지 않고, 아홉을 세기도 쉬워진다
 *
 * 꼬리끼리 한 덩어리로 뭉치지 않도록 **꼬리마다** 어두운 테를 먼저 깔고 그 위에
 * 몸색을 얹는다. 전부 깔고 전부 칠하면 뒤 꼬리의 테가 앞 꼬리에 덮여 사라진다.
 *
 * @param tails `[각도(도, 180이 왼쪽), 길이, 휨]` 아홉 쌍.
 */
function foxTails(
  bx: number,
  by: number,
  tails: readonly (readonly [number, number, number])[],
): ArtLayer[] {
  const layers: ArtLayer[] = []

  for (const [deg, len, bow] of tails) {
    const a = (deg * Math.PI) / 180
    const dx = Math.cos(a)
    const dy = Math.sin(a)
    // 진행 방향의 법선 — 휨을 이 축으로 준다
    const nx = -dy
    const ny = dx
    const tipX = bx + dx * len + nx * bow
    const tipY = by + dy * len + ny * bow
    const cx = bx + dx * len * 0.55 + nx * bow * 1.9
    const cy = by + dy * len * 0.55 + ny * bow * 1.9

    const d = `M${r1(bx)} ${r1(by)} Q${r1(cx)} ${r1(cy)} ${r1(tipX)} ${r1(tipY)}`
    layers.push({ d, stroke: 'rgba(0,0,0,0.45)', width: 4.5 })
    layers.push({ d, stroke: '@color', width: 3.5 })

    // 흰 끝은 **꼬리와 같은 굵기의 짧은 토막**으로 그린다.
    //
    // 함정이 세 번 있었다.
    //   1. 끝점에 원을 얹었더니 원이 꼬리보다 굵어 보여 성냥개비가 됐다.
    //   2. 원호(`A`)로 그리면 두 끝점이 같은 좌표로 반올림될 때 SVG가 호를
    //      통째로 버린다 — 흰 끝이 전부 사라졌다. 토막으로 바꿔 해결.
    //   3. 토막을 길게(0.72) 잡으면 흰 부분끼리 겹쳐 붙어 꼬리를 삼킨다.
    // 그래서 거의 점에 가깝게 잡되(둥근 끝 덕에 길이가 0이어도 굵기만큼은
    // 칠해진다), **꼬리 하나를 그린 직후 그 꼬리의 끝을 바로 칠한다**.
    // 흰 끝을 전부 맨 위에 몰아 그렸더니 뒤 꼬리의 어두운 테가 앞 꼬리의
    // 몸통만 깎고 흰 끝은 못 깎아, 끝이 몸통보다 굵어 보였다.
    const t = 0.96
    const nearX = (1 - t) * (1 - t) * bx + 2 * (1 - t) * t * cx + t * t * tipX
    const nearY = (1 - t) * (1 - t) * by + 2 * (1 - t) * t * cy + t * t * tipY
    layers.push({
      d: `M${r1(nearX)} ${r1(nearY)} L${r1(tipX)} ${r1(tipY)}`,
      stroke: '@accent',
      width: 3.1,
    })
  }

  return layers
}

