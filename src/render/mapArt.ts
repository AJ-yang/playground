/**
 * 타이틀 배경의 조선 고지도.
 *
 * 이 게임의 스테이지는 왜구의 노략에서 병자호란까지 **실제 전쟁을 순서대로**
 * 따라간다. 그렇다면 첫 화면이 말해야 할 것은 "성을 지킨다"가 아니라
 * **"어디를, 누구에게서, 어떤 순서로 지키는가"** 다. 지도 한 장이 그 셋을
 * 동시에 말한다 — 여섯 전장이 찍히고, 침입 화살이 남과 북에서 들어오고,
 * 깬 곳과 못 깬 곳이 표식으로 갈린다.
 *
 * 형식은 조선 후기 관찬 지도를 따랐다.
 *   - **방안(方眼)**: 동국지도 계열이 쓰던 눈금. 축척을 재려고 그은 격자다.
 *   - **산줄기**: 백두대간을 낱개 봉우리 기호로 잇는다. 조선 지도는 산을
 *     등고선이 아니라 이어진 봉우리 그림으로 그렸다.
 *   - **물줄기**: 두 줄 평행선. 폭이 아니라 흐름을 나타낸다.
 *   - **읍호(邑號)**: 지명을 원이나 사각 테두리로 감싼다.
 *
 * 좌표는 100 × 140 정규 공간이고, 그리는 쪽에서 원하는 크기로 옮긴다.
 * 실측 지도가 아니라 **형태의 기호**다 — 서해안이 들쭉날쭉하고 동해안이
 * 곧은 것, 산줄기가 북동에서 남서로 흐르는 것 정도만 지킨다.
 */

