/**
 * 여섯 전장. `stage`는 STAGES의 index(1부터)와 맞춘다.
 *
 * 위치는 사건이 벌어진 곳을 따른다. 게임의 맵 이름(예: S3 「새재 갈림길」)이
 * 아니라 **전쟁이 실제로 일어난 곳**을 찍어야 지도가 역사를 말한다 —
 * 니탕개의 난은 함경도 육진이지 새재가 아니다.
 */
export interface WarSite {
  stage: number
  name: string
  x: number
  y: number
  /** 지명을 표식의 어느 쪽에 놓을지 */
  side: 'left' | 'right'
}

